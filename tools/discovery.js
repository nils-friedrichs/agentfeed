/**
 * OpenAPI `responses` entries for the error statuses a paid route really emits.
 *
 * CDP's curation bar asks for documented error responses. Every status, body and
 * limit here came out of the code; the 400 example is a response that was
 * actually observed against a free-mode boot, and a route with no input
 * validation is given no invented example. The MPP note is preserved for the two
 * routes that carry a second payment protocol.
 */
function openApiErrors(pattern, mpp, tempo) {
  const out = {};
  const route = ERROR_META.routes[pattern] || {};
  for (const e of ERROR_META.shared || []) {
    // a shared status that only some routes can answer (422) is documented on those only
    if (Array.isArray(e.appliesTo) && !e.appliesTo.includes(pattern)) continue;
    const r = { description: e.when + (e.note ? ` ${e.note}` : '') };
    const solana = mpp && mpp.active && mpp.routes.includes(pattern);
    const tempoOn = tempo && tempo.active;
    if (e.status === 402 && (solana || tempoOn)) {
      const methods = [tempoOn ? 'tempo/charge' : null, solana ? 'solana/charge' : null].filter(Boolean).join(' and ');
      r.description = r.description.replace(
        'PAYMENT-REQUIRED response header',
        `PAYMENT-REQUIRED response header, and MPP (${methods}) in WWW-Authenticate`,
      );
    }
    if (e.status === 402) {
      r.headers = { 'PAYMENT-REQUIRED': { description: 'Base64 x402 v2 challenge. The body is the same challenge as x402 v1 (Base and Solana).', schema: { type: 'string' } } };
      if (solana || tempoOn) r.headers['WWW-Authenticate'] = { description: 'MPP Payment challenges, one per method and token: tempo/charge (chain 4217, OUSD then USDC.e, pull mode)' + (solana ? ', and solana/charge' : '') + '. PAYMENT-REQUIRED is unchanged by them.', schema: { type: 'string' } };
    }
    if (e.status === 429 || e.status === 503) r.headers = { 'Retry-After': { description: 'Seconds to wait.', schema: { type: 'integer' } } };
    if (e.status === 405) r.headers = { Allow: { description: 'Always GET.', schema: { type: 'string' } } };
    if (e.status === 400 && route.callerError) {
      r.description += ` Observed: ${route.callerError.violated}.`;
    } else if (e.status === 400 && Array.isArray(route.requiredInputs) && !route.requiredInputs.length) {
      r.description += ' This route takes no required input, so a 400 means an upstream source failed, not a caller mistake.';
    }
    const example = e.status === 400 && route.callerError ? route.callerError.body : e.body;
    if (example !== null && example !== undefined) {
      r.content = { 'application/json': { schema: { type: 'object' }, example } };
    }
    out[e.status] = r;
  }
  return out;
}

// ---- shared helpers ------------------------------------------------------

/** `/api/token-risk/:mint` -> `{ template: '/api/token-risk/{mint}', names: ['mint'] }` */
function toTemplate(p) {
  const names = [];
  const template = p.replace(/:([A-Za-z0-9_]+)/g, (_m, name) => { names.push(name); return `{${name}}`; });
  return { names, template };
}

function humanize(tool) {
  return tool.replace(/^get_/, '').split('_').filter(Boolean)
    .map((w) => (/^(sol|btc|eth|usd|oi|tvl|dex|api)$/i.test(w) ? w.toUpperCase() : w)).join(' ');
}

function cutAtWord(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const sp = cut.lastIndexOf(' ');
  return (sp > max * 0.6 ? cut.slice(0, sp) : cut).replace(/[\s,:;.\-]+$/, '');
}

// `pay catalog check` renders the summary inside the OS biometric prompt, which
// truncates at 64, and rejects superlatives and cost claims in it. Derived from
// the tool name plus the opening gist so a new route gets one for free.
const SUMMARY_MAX = 63;
const SUMMARY_MIN = 24;
function summaryFor(tool, description) {
  const subject = humanize(tool);
  const gist = String(description || '')
    .replace(/^[A-Z][A-Z\s-]{3,}:\s*/, '').split(/[.:(]/)[0].trim().toLowerCase()
    .replace(/\b(best|fastest|cheapest|largest|biggest|leading|premium|only|complete|flagship)\b\s*/g, '')
    .replace(/\s{2,}/g, ' ').trim();
  let summary = gist ? cutAtWord(`Fetch ${subject}: ${gist}`, SUMMARY_MAX) : `Fetch ${subject}`;
  if (summary.length < SUMMARY_MIN) summary = `Fetch ${subject} from the AgentFeed API`;
  if (summary.length > SUMMARY_MAX) summary = cutAtWord(summary, SUMMARY_MAX);
  return summary;
}

function schemaFor(prop) {
  const out = {};
  if (prop.type) out.type = prop.type;
  if (prop.enum) out.enum = prop.enum;
  if (prop.description) out.description = prop.description;
  if (prop.default !== undefined) out.default = prop.default;
  if (!Object.keys(out).length) out.type = 'string';
  return out;
}

